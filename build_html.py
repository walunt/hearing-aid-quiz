def parse_similar(lines):
    groups = []
    cur = None
    for raw in lines:
        line = raw.strip()
        if not line:
            continue
        # 小节标题（"一、易混相似题…" / "二、表述变体…" / "第二部分…"）是分组边界：
        # 关闭当前组，且不把标题本身吸入任何组
        if re.match(r"^(一、|二、|三、|第一部分|第二部分|第三部分)", line):
            if cur:
                groups.append(cur)
            cur = None
            continue
        # 变体标记可独占一行或与内容同行："【变体 1】xxx"
        vm = re.match(r"^(【变体\s*\d+】)(.*)$", line)
        cm = re.match(r"^(【对比\s*\d+】)$", line)
        if vm or cm:
            if cur:
                groups.append(cur)
            cur = {"type": (vm or cm).group(1), "lines": [], "title": "", "ans_list": [],
                   "diff": "", "variant": "", "shared_ans": ""}
            # 若变体标记与内容同行，把剩余内容作为 variant 文本
            if vm and vm.group(2).strip():
                cur["variant"] = vm.group(2).strip()
            continue
        if cur is None:
            continue
        if line.startswith("题 A："):
            cur["lines"].append(("A", line[4:].strip()))
        elif line.startswith("题 B："):
            cur["lines"].append(("B", line[4:].strip()))
        elif line.startswith("答案相同："):
            cur["shared_ans"] = line[5:].strip()
        elif line.startswith("答案："):
            # 对比组每题各有答案行（题 A→题 B 顺序），按序存储，渲染时挂到对应题
            cur["ans_list"].append(line[3:].strip())
        elif line.startswith("差异点："):
            cur["diff"] = line[3:].strip()
        elif re.search(r".*≈.*", line):
            cur["variant"] = line
        else:
            # 变体组的补充描述（如『答案相同』已单独捕获）；其余忽略
            if re.search(r"题干.*≈.*题干|答案相同.*≈", line):
                cur["variant"] = line
            # 对比组的题干补充行
            elif cur["type"].startswith("【对比") and line:
                cur["lines"].append(("N", line))
    if cur:
        groups.append(cur)
    return groups

