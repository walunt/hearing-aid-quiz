from difflib import SequenceMatcher
def _norm(s):
    return re.sub(r"[\s【】（）()《》。，、；：？?！!\-\.\u00d7:·]", "", s)
def _find_bank(stem):
    ns = _norm(stem); best = None; bs = 0
    for q in BANK:
        r = SequenceMatcher(None, ns, _norm(q["s"])).ratio()
        if r > bs:
            bs = r; best = q
    return best if bs >= 0.60 else None
