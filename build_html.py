def match_knowledge(stem):
    s = norm_stem(stem)
    best = None; best_score = 0
    for key, entry in KNOWLEDGE.items():
        score = 0; mlen = 0; spec = []
        for tag in entry["tags"]:
            if tag and tag in s:
                if len(tag) < 2 or tag in GENERIC_TAGS:
                    score += 2           # 通用/单字词：仅弱加分，不作为判据
                else:
                    score += 100         # 强特征词：主要判据
                    spec.append(tag)
                mlen = max(mlen, len(tag))
        # 只要命中一个"非通用强特征词"（长度≥2且不在通用词表）即信任该知识点
        if spec:
            sc = score * 10 + mlen
            if sc > best_score:
                best_score = sc; best = key
    return best

def explain(q):
    ans_letters = list(q["a"])
    # 逐题覆盖优先：Q_OVERRIDE 按题号精确指定（考察点, 解析），规避关键词匹配错配
    if q["n"] in Q_OVERRIDE:
        key, body = Q_OVERRIDE[q["n"]]
    else:
        key = match_knowledge(q["s"])
        body = KNOWLEDGE[key]["exp"] if key else ""
    if q["multi"]:
        correct_texts = [x["t"] for x in q["o"] if x["k"] in ans_letters]
        head = "正确答案：" + "、".join(f"{x['k']}){x['t']}" for x in q["o"] if x["k"] in ans_letters)
        # 说明漏选/错选提示
        wrong_texts = [x["t"] for x in q["o"] if x["k"] not in ans_letters]
        note = f"（{len(ans_letters)} 项正确：{ans_letters}）本题为多选题，需选全所有正确项。"
    else:
        ans = next((x for x in q["o"] if x["k"] == q["a"]), None)
        head = f"正确答案：{q['a']}）{ans['t'] if ans else ''}"
        note = ""
    return {"title": f"考察点：{key if key else '综合'}", "text": head + "\n\n" + body + ("" if note=="" else ("\n\n" + note))}

