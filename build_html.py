W = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"

def para_text(p):
    parts = []
    for node in p.iter():
        if node.tag == W + "t":
            parts.append(node.text or "")
        elif node.tag == W + "tab":
            parts.append("\t")
        elif node.tag == W + "br":
            parts.append("\n")
    return "".join(parts)

def extract_docx(path):
    with zipfile.ZipFile(path) as z:
        xml = z.read("word/document.xml").decode("utf-8", "ignore")
    root = ET.fromstring(xml)
    body = root.find(W + "body")
    def walk(el):
        for c in el:
            if c.tag == W + "p":
                yield para_text(c).strip()
            elif c.tag == W + "tbl":
                for tr in c.findall(W + "tr"):
                    cells = [ "".join(walk(tc)).strip() for tc in tr.findall(W + "tc") ]
                    yield " || ".join(cells)
            else:
                yield from walk(c)
    return [l for l in walk(body) if l.strip()]

