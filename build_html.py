# 2) 题库解析（容忍空格 A ）x、笔误 D0x、顿号 A、x）
# ============================================================================
OPT_LINE = re.compile(r"^[A-E]\s*[）.)、:0]")
OPT_PART = re.compile(r"^([A-E])\s*[）.)、:0]\s*(.*)$")
ANS_SEG  = re.compile(r"^[ \t]*([A-E])\s*[）.)、:0]*")

def parse_questions(lines):
    qs = []
    cur = None
    for raw in lines:
        line = raw.strip()
        if not line:
            continue
        m = re.match(r"^(\d+)\.\s*(.*)$", line)
        if m:
            if cur and cur.get("s"):
                qs.append(cur)
            stem = m.group(2).strip()
            cur = {"n": int(m.group(1)), "s": stem, "o": [], "a": None,
                   "multi": "【多选题】" in stem or "【多选】" in stem}
            continue
        m2 = re.match(r"^【答案】\s*(.*)$", line)
        if m2 and cur is not None:
            segs = [s.strip() for s in m2.group(1).split("；") if s.strip()]
            cur["a"] = "".join(ANS_SEG.match(s).group(1) for s in segs if ANS_SEG.match(s))
            continue
        if cur is not None and OPT_LINE.match(line):
            for part in line.split("||"):
                pm = OPT_PART.match(part.strip())
                if pm:
                    cur["o"].append({"k": pm.group(1), "t": pm.group(2).strip()})
    if cur and cur.get("s"):
        qs.append(cur)
    return [q for q in qs if q.get("s")]

