def group_title(g):
    m = re.search(r"【(对比|变体)\s*(\d+)】", g["type"])
    if not m:
        return g["type"]
    axis, num = m.group(1), m.group(2)
    if axis == "对比":
        return SIM_TITLES.get("对比" + num, g["type"])
    return "表述变体：同一考点之不同说法"

